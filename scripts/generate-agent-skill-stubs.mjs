import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, ".llm", "skills");
const destinations = [".agents", ".claude"];
const generator = "scripts/generate-agent-skill-stubs.mjs";
const mode = process.argv[2];

if (mode !== "--write" && mode !== "--check") {
  process.stderr.write(`Usage: node ${generator} --write|--check\n`);
  process.exit(2);
}

const skillFiles = fs
  .readdirSync(sourceDirectory)
  .filter((name) => name.endsWith(".md") && name !== "index.md")
  .sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
const expected = new Map();

for (const filename of skillFiles) {
  const name = path.basename(filename, ".md");
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`Invalid skill name: ${filename}`);
  }

  const source = fs.readFileSync(path.join(sourceDirectory, filename), "utf8");
  const trigger = source.match(/<!--\s*trigger:\s*([^\r\n]*?)\s*-->/);
  if (!trigger) {
    throw new Error(`Missing trigger comment: ${filename}`);
  }

  const fields = trigger[1].split("|").map((field) => field.trim());
  if (fields.length < 2 || fields.length > 3 || !fields[0] || !fields[1]) {
    throw new Error(`Malformed trigger comment: ${filename}`);
  }

  const description = fields[1];
  if (description.length > 1024) {
    throw new Error(`Description exceeds 1024 characters: ${filename}`);
  }

  const title = name
    .split("-")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");
  const contents = [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    `# ${title}`,
    "",
    `Read and follow the [canonical skill](../../../.llm/skills/${filename}).`,
    "",
    `<!-- Generated by ${generator}; edit the canonical skill instead. -->`,
    ""
  ].join("\n");
  expected.set(name, contents);
}

let failures = 0;
for (const destination of destinations) {
  const skillsDirectory = path.join(root, destination, "skills");
  if (fs.existsSync(skillsDirectory)) {
    for (const item of fs.readdirSync(skillsDirectory, { withFileTypes: true })) {
      if (!item.isDirectory() || expected.has(item.name)) continue;
      const directory = path.join(skillsDirectory, item.name);
      const file = path.join(directory, "SKILL.md");
      if (!fs.existsSync(file)) continue;
      const contents = fs.readFileSync(file, "utf8");
      const generated = contents.includes(`<!-- Generated by ${generator}; edit the canonical skill instead. -->`);
      if (mode === "--write" && generated && fs.readdirSync(directory).length === 1) {
        fs.rmSync(directory, { recursive: true });
        continue;
      }
      process.stderr.write(`Unexpected discovery skill: ${destination}/skills/${item.name}\n`);
      failures++;
    }
  }

  for (const [name, contents] of expected) {
    const file = path.join(skillsDirectory, name, "SKILL.md");
    if (mode === "--write") {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents, "utf8");
    } else if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== contents) {
      process.stderr.write(`Missing or stale discovery skill: ${destination}/skills/${name}/SKILL.md\n`);
      failures++;
    }
  }
}

if (failures) {
  process.stderr.write(`${failures} discovery skill mismatch(es). Run node ${generator} --write.\n`);
  process.exit(1);
}

process.stdout.write(`${mode === "--write" ? "Generated" : "Validated"} ${expected.size} skills for each agent directory.\n`);
