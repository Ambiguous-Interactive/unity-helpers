"""Require block form for multiline ordinary comments inside C# types and members."""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from cli_encoding import configure_output, escape_command_data
from csharp_sources import is_link, source_files, source_tokens

ROOT = Path(__file__).resolve().parents[1]
ROOTS = ("Runtime", "Editor", "Tests", "Generator~")
DIRECTIVE = re.compile(
    r"^//\s*(UNH-SUPPRESS|cspell:|ReSharper|Justification:|<auto-generated)",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class Violation:
    """A consecutive run with its original lines and safe conversion decision."""

    line: int
    end_line: int
    indent: int
    body: tuple[str, ...]
    first: str
    convertible: bool


def analyze(text: str) -> list[Violation]:
    """Identify standalone ordinary line-comment runs using the shared C# scanner."""
    standalone: list[tuple[int, int, str]] = []
    line = 1
    cursor = 0
    for start, end, kind in source_tokens(text):
        if kind != "line" or text.startswith("///", start):
            continue
        line += text.count("\n", cursor, start)
        cursor = start
        prefix = text[text.rfind("\n", 0, start) + 1 : start]
        if prefix.strip():
            continue
        standalone.append((line, len(prefix), text[start:end].rstrip("\r")))
    found: list[Violation] = []
    first = 0
    while first < len(standalone):
        last = first + 1
        while last < len(standalone) and standalone[last][0] == standalone[last - 1][0] + 1:
            last += 1
        run = standalone[first:last]
        if (
            len(run) >= 2
            and all(indent >= 8 for _, indent, _ in run)
            and not all(DIRECTIVE.match(comment) for _, _, comment in run)
        ):
            body = tuple(comment[2:].removeprefix(" ") for _, _, comment in run)
            found.append(
                Violation(
                    run[0][0],
                    run[-1][0],
                    run[0][1],
                    body,
                    run[0][2][:70],
                    not any("/*" in value or "*/" in value for value in body),
                )
            )
        first = last
    return found


def rewrite(text: str, violations: list[Violation]) -> tuple[str, int]:
    """Convert safe runs while retaining newline style, final newline, and declined runs."""
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.replace("\r\n", "\n").split("\n")
    declined = 0
    for violation in reversed(violations):
        if not violation.convertible:
            declined += 1
            continue
        pad = " " * violation.indent
        replacement = [pad + "/*"]
        replacement.extend(
            pad + "    " + value if value.strip() else "" for value in violation.body
        )
        replacement.append(pad + "*/")
        lines[violation.line - 1 : violation.end_line] = replacement
    return newline.join(lines), declined


def checked_path(repository: Path, name: str) -> Path:
    """Refuse absent, linked, special, or outside-repository writable inputs."""
    path = Path(os.path.abspath(repository / name.replace("\\", "/")))  # noqa: PTH100
    if not path.is_relative_to(repository):
        raise ValueError(f"Source is outside the repository: {name}")
    current = path
    while True:
        if is_link(current):
            raise ValueError(f"Source is linked: {name}")
        if current == repository:
            break
        current = current.parent
    if not path.is_file():
        raise ValueError(f"Source is not a regular file: {name}")
    return path


def files_to_check(repository: Path, paths: list[str] | None, *, fixture: bool) -> list[Path]:
    """Discover Git-owned and untracked sources or a complete external fixture corpus."""
    if not repository.is_dir() or is_link(repository):
        raise ValueError(f"Repository is missing or linked: {repository}")
    if paths:
        names = sorted({name for name in paths if name.lower().endswith(".cs")})
    elif fixture:
        names = [
            path.relative_to(repository).as_posix() for path in source_files(repository, ROOTS)
        ]
    else:
        git = shutil.which("git")
        if git is None:
            raise ValueError("Git is required to discover C# sources")
        result = subprocess.run(  # noqa: S603 - fixed Git arguments, no shell.
            [
                git,
                "-C",
                str(repository),
                "ls-files",
                "-z",
                "--cached",
                "--others",
                "--exclude-standard",
                "--",
                *(f"{root}/*.cs" for root in ROOTS),
            ],
            capture_output=True,
            check=True,
            timeout=30,
        )
        names = sorted(set(result.stdout.decode("utf-8").rstrip("\0").split("\0")))
    selected: list[Path] = []
    for name in names:
        if not name:
            continue
        path = checked_path(repository, name)
        if path.relative_to(repository).as_posix().startswith("Runtime/Utils/SevenZip/"):
            continue
        selected.append(path)
    return selected


def main(argv: list[str] | None = None) -> int:
    """Run the comment policy and optional safe conversions with explicit scan counts."""
    configure_output()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path)
    parser.add_argument("--paths", nargs="+")
    parser.add_argument("--fix", action="store_true")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args(argv)
    repository = Path(os.path.abspath(args.repo_root or ROOT))  # noqa: PTH100
    try:
        paths = files_to_check(repository, args.paths, fixture=args.repo_root is not None)
        counts = dict.fromkeys(ROOTS, 0)
        sources: list[tuple[Path, str, list[Violation]]] = []
        for path in paths:
            relative = path.relative_to(repository).as_posix()
            root = relative.split("/", 1)[0]
            if root in counts:
                counts[root] += 1
            try:
                text = path.read_bytes().decode("utf-8-sig")
            except (OSError, UnicodeError) as error:
                raise ValueError(f"{relative}: {error}") from error
            sources.append((path, text, analyze(text)))
        if not args.paths:
            for root, count in counts.items():
                if count == 0:
                    raise ValueError(
                        f"{root}/ yielded no C# files; this run examined nothing there"
                    )
        violations = sum(len(found) for _, _, found in sources)
        if args.fix:
            rewritten = declined = 0
            for path, text, found in sources:
                result, refused = rewrite(text, found)
                declined += refused
                if result != text:
                    path.write_bytes(result.encode("utf-8"))
                    rewritten += 1
            print(
                f"[lint-comment-block-form] Rewrote {rewritten} file(s); declined {declined} run(s) whose text carries a comment delimiter."
            )
            return 0
        if violations:
            print(f"[lint-comment-block-form] {violations} multi-line // comment run(s).")
            print("Delete the run, or write it as one /* ... */ block. See .llm/context.md rule 8.")
            for path, _, found in sources:
                for violation in found:
                    relative = escape_command_data(path.relative_to(repository).as_posix())
                    print(
                        f"  {relative}:{violation.line}  {violation.end_line - violation.line + 1} lines  {escape_command_data(violation.first)}"
                    )
            return 1
        summary = ", ".join(f"{root}/ {count}" for root, count in counts.items())
        print(f"[lint-comment-block-form] Scanned {summary} file(s); 0 multi-line // comment runs.")
        return 0
    except (OSError, UnicodeError, ValueError, subprocess.SubprocessError) as error:
        print(f"[lint-comment-block-form] ERROR: {escape_command_data(str(error))}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
