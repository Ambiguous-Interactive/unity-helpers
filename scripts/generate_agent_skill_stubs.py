"""Generate agent discovery stubs from the canonical skill descriptions."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from cli_encoding import configure_output

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = "scripts/generate-agent-skill-stubs.mjs"
MARKER = f"<!-- Generated by {GENERATOR}; edit the canonical skill instead. -->"
DESTINATIONS = (".agents", ".claude")
JAVASCRIPT_WHITESPACE = "\t\n\v\f\r \u00a0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a\u2028\u2029\u202f\u205f\u3000\ufeff"
SPACE_PATTERN = f"[{re.escape(JAVASCRIPT_WHITESPACE)}]"
TRIGGER = re.compile(rf"<!--{SPACE_PATTERN}*trigger:{SPACE_PATTERN}*([^\r\n]*?){SPACE_PATTERN}*-->")


def require_owned_path(path: Path) -> None:
    if path.resolve() != path.absolute():
        raise ValueError(f"Refusing a linked skill path: {path}")


def expected_stubs(root: Path) -> dict[str, bytes]:
    source_directory = root / ".llm" / "skills"
    require_owned_path(source_directory)
    files = sorted(
        (
            item
            for item in source_directory.iterdir()
            if item.name.endswith(".md") and item.name != "index.md"
        ),
        key=lambda item: item.name.encode("utf-16-be", errors="surrogatepass"),
    )
    if not files:
        raise ValueError("Skill discovery found zero canonical skills.")
    expected: dict[str, bytes] = {}
    for source in files:
        name = source.stem
        if re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) is None:
            raise ValueError(f"Invalid skill name: {source.name}")
        require_owned_path(source)
        trigger = TRIGGER.search(source.read_text(encoding="utf-8", errors="replace"))
        if trigger is None:
            raise ValueError(f"Missing trigger comment: {source.name}")
        fields = [field.strip(JAVASCRIPT_WHITESPACE) for field in trigger.group(1).split("|")]
        if len(fields) not in (2, 3) or not fields[0] or not fields[1]:
            raise ValueError(f"Malformed trigger comment: {source.name}")
        description = fields[1]
        if len(description.encode("utf-16-le", errors="surrogatepass")) // 2 > 1024:
            raise ValueError(f"Description exceeds 1024 characters: {source.name}")
        title = " ".join(word[0].upper() + word[1:] for word in name.split("-"))
        contents = "\n".join(
            (
                "---",
                f"name: {name}",
                f"description: {json.dumps(description, ensure_ascii=False)}",
                "---",
                "",
                f"# {title}",
                "",
                f"Read and follow the [canonical skill](../../../.llm/skills/{source.name}).",
                "",
                MARKER,
                "",
            )
        )
        expected[name] = contents.encode("utf-8")
    return expected


def generate(root: Path, *, write: bool) -> int:
    root = root.resolve()
    expected = expected_stubs(root)
    stale: list[str] = []
    removals: list[Path] = []
    writes: list[tuple[Path, bytes]] = []
    for destination in DESTINATIONS:
        directory = root / destination / "skills"
        require_owned_path(directory)
        if directory.exists():
            for item in sorted(directory.iterdir()):
                if item.is_symlink() or not item.is_dir() or item.name in expected:
                    continue
                require_owned_path(item)
                file = item / "SKILL.md"
                require_owned_path(file)
                if not file.is_file():
                    continue
                generated = MARKER in file.read_text(encoding="utf-8", errors="replace")
                if write and generated and len(list(item.iterdir())) == 1:
                    removals.append(item)
                else:
                    stale.append(f"Unexpected discovery skill: {destination}/skills/{item.name}")
        for name, contents in expected.items():
            file = directory / name / "SKILL.md"
            require_owned_path(file)
            if file.is_file() and file.read_bytes() == contents:
                continue
            if write:
                writes.append((file, contents))
            else:
                stale.append(f"Missing or stale discovery skill: {destination}/skills/{name}")
    for directory in removals:
        require_owned_path(directory / "SKILL.md")
        (directory / "SKILL.md").unlink()
        directory.rmdir()
    for file, contents in writes:
        require_owned_path(file)
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(contents)
    if stale:
        for message in stale:
            print(message, file=sys.stderr)
        print(
            f"{len(stale)} discovery skill mismatch(es). Run node {GENERATOR} --write.",
            file=sys.stderr,
        )
        return 1
    verb = "Generated" if write else "Validated"
    print(f"{verb} {len(expected)} skills for each agent directory.")
    return 0


def main(arguments: list[str] | None = None, *, root: Path = ROOT) -> int:
    configure_output()
    arguments = sys.argv[1:] if arguments is None else arguments
    mode = arguments[0] if arguments else None
    if mode not in ("--write", "--check"):
        print(f"Usage: node {GENERATOR} --write|--check", file=sys.stderr)
        return 2
    try:
        return generate(root, write=mode == "--write")
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
