"""Render the older-editor workflow from the licensed Unity job definitions."""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Sequence

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ".github/workflows/unity-tests.yml"
TARGET = ".github/workflows/unity-compatibility.yml"
LAUNCHER = "scripts/unity/generate-compatibility-workflow.js"
JOBS = ("matrix-config", "runner-preflight", "unity-tests", "unity-tests-aggregate")
READBACK_GUARD = (
    "!(github.event_name == 'workflow_dispatch' && inputs.native-readback-run-id != '') && "
)
DISPATCH_DEFAULTS = {
    "unity-version": "''",
    "native-readback-run-id": "''",
    "native-readback-build-receipt-sha256": "''",
    "acceptance": "'none'",
    "latest-mode-scheduling": "'split'",
    "test-mode": "'all'",
    "fresh-conversion": "false",
    "intmap-diagnostics": "false",
    "native-diagnostics": "false",
    "native-build-direct-control": "false",
    "native-debugger-standard-heap": "false",
    "native-build-attach-control": "false",
    "native-build-attach-after-startup": "false",
    "native-build-attach-after-shutdown": "false",
    "native-loader-snaps-comparison": "false",
}
HEADER = (
    f"# Generated by {LAUNCHER}. Do not edit.\n"
    """name: Unity Compatibility

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  checks: write
  pull-requests: read

concurrency:
  group: unity-compatibility-${{ github.sha }}
  cancel-in-progress: true

jobs:
"""
)


def dispatch_default(match: re.Match[str]) -> str:
    field = match[1]
    try:
        return DISPATCH_DEFAULTS[field]
    except KeyError as error:
        raise ValueError(f"Unclassified Unity dispatch input: {field}") from error


def include_step(step: str) -> bool:
    condition = re.search(r"(?m)^        if:[^\n]*(?:\n {10,}[^\n]*)*", step)
    return condition is None or (
        "inputs.latest-mode-scheduling" not in condition[0]
        and "needs.matrix-config.outputs.combine-variants" not in condition[0]
    )


def render_job(job: str, block: str) -> str:
    block = block.replace(READBACK_GUARD, "")
    if job == "unity-tests-aggregate":
        block = block.replace("if: ${{ (always()) }}", "if: ${{ always() }}", 1)
    block = re.sub(
        r"(?m)^    name: (.+)$",
        lambda name: (
            "    name: Unity Compatibility Success"
            if job == "unity-tests-aggregate"
            else f"    name: Compatibility {name[1]}"
        ),
        block,
        count=1,
    )
    block = "".join(filter(include_step, re.split(r"(?m)(?=^      - name: )", block)))
    block = re.sub(r"inputs\.([a-z][a-z0-9-]*)", dispatch_default, block)
    if job == "matrix-config":
        block = re.sub(
            r"(?m)^      combine-variants: >-\n(?: {8,}[^\n]*\n)+",
            '      combine-variants: "false"\n',
            block,
            count=1,
        )
        block = block.replace(
            "          INPUT_UNITY_VERSION:",
            "          INPUT_UNITY_COVERAGE: compatibility\n          INPUT_UNITY_VERSION:",
            1,
        )
    if job in {"matrix-config", "unity-tests"}:
        block = re.sub(
            r"(    if: >-\n      \$\{\{ |    if: \$\{\{ )",
            r"\1github.ref == 'refs/heads/main' && github.ref_protected && ",
            block,
            count=1,
        )
    if job == "runner-preflight":
        block = re.sub(
            r"      group: >-\n(?:        .*\n)+",
            "      group: ${{ github.workflow }}-runner-preflight-${{ github.sha }}\n",
            block,
            count=1,
        )
        block = re.sub(
            r"          required-label-sets: >-\n(?:            .*\n?)+",
            """          required-label-sets: '[["self-hosted","Windows","RAM-64GB","DAD-MACHINE"]]'\n""",
            block,
            count=1,
        )
    if job == "unity-tests":
        block = block.replace(
            "    runs-on: [self-hosted, Windows, RAM-64GB]",
            "    runs-on: [self-hosted, Windows, RAM-64GB, DAD-MACHINE]",
            1,
        )
        block = re.sub(
            r"      # No max-parallel[\s\S]*?(?=      # The enrollment audit)",
            "      # Keep one runner available for new fast validation.\n",
            block,
            count=1,
        )
        block = block.replace("    strategy:\n", "    strategy:\n      max-parallel: 1\n", 1)
    return block


def render_compatibility_workflow(source: str) -> str:
    jobs = source.partition("\njobs:\n")[2]
    matches = list(re.finditer(r"(?m)^  ([a-z][a-z0-9-]*):$", jobs))
    boundaries = [*(match.start() for match in matches), len(jobs)]
    blocks = {
        match[1]: jobs[match.start() : end].rstrip()
        for match, end in zip(matches, boundaries[1:], strict=True)
    }
    rendered: list[str] = []
    for job in JOBS:
        if job not in blocks:
            raise ValueError(f"Canonical Unity workflow is missing {job}.")
        rendered.append(render_job(job, blocks[job]))
    return HEADER + "\n\n".join(rendered) + "\n"


def generated_workflow(root: Path) -> bytes:
    source = (root / SOURCE).read_bytes().decode("utf-8")
    content = render_compatibility_workflow(source)
    result = subprocess.run(  # noqa: S603 - fixed repository-local formatter with stdin.
        [
            sys.executable,
            str(ROOT / "scripts/run_node_bin.py"),
            "prettier",
            "--parser",
            "yaml",
            "--no-config",
            "--no-editorconfig",
        ],
        input=content.encode("utf-8"),
        capture_output=True,
        cwd=ROOT,
        timeout=60,
        check=False,
    )
    if result.returncode:
        message = result.stderr.decode("utf-8", errors="replace").strip()
        raise ValueError(message or f"Prettier exited with status {result.returncode}.")
    return result.stdout


def publish_workflow(target: Path, content: bytes) -> None:
    target = target.resolve()
    descriptor, name = tempfile.mkstemp(
        prefix=".unity-compatibility-", suffix=".tmp", dir=target.parent
    )
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
        if target.is_file():
            shutil.copymode(target, temporary)
        else:
            temporary.chmod(0o644)
        temporary.replace(target)
    finally:
        temporary.unlink(missing_ok=True)


def main(arguments: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--repo-root", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--stdout", action="store_true")
    mode.add_argument("--raw", action="store_true")
    args = parser.parse_args(arguments)
    try:
        if args.raw:
            source = sys.stdin.buffer.read().decode("utf-8")
            sys.stdout.buffer.write(render_compatibility_workflow(source).encode("utf-8"))
            return 0
        content = generated_workflow(args.repo_root)
        target = args.repo_root / TARGET
        if args.stdout:
            sys.stdout.buffer.write(content)
        elif args.check:
            if not target.is_file() or target.read_bytes() != content:
                raise ValueError(f"Run node {LAUNCHER} to update {TARGET}.")
        else:
            publish_workflow(target, content)
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
