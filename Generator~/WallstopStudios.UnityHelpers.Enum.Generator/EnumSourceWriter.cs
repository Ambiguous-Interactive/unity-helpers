namespace WallstopStudios.UnityHelpers.Enum.Generator
{
    using System.Globalization;
    using System.Text;
    using Microsoft.CodeAnalysis.CSharp;

    /// <summary>Writes the generated fast-path class for one annotated enum.</summary>
    internal static class EnumSourceWriter
    {
        private const string GeneratorName = "WallstopStudios.UnityHelpers.Enum.Generator";

        public static string Write(EnumGenerationPlan plan, StringBuilder builder)
        {
            builder.Clear();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#pragma warning disable CS0618");
            if (plan.Namespace != null)
            {
                builder.Append("namespace ").Append(plan.Namespace).AppendLine().AppendLine("{");
            }
            AppendUsings(builder);
            AppendClassHeader(builder, plan);
            AppendFlagMethods(builder, plan);
            AppendNameTable(builder, plan, "Names", false);
            AppendDisplayTable(builder, plan);
            AppendNameLookup(builder, plan);
            AppendDisplayLookup(builder, plan);
            AppendNameMethods(builder, plan);
            AppendFormatMethod(builder, plan);
            builder.AppendLine("    }");
            if (plan.Namespace != null)
            {
                builder.AppendLine("}");
            }
            return builder.ToString();
        }

        private static void AppendUsings(StringBuilder builder)
        {
            builder.AppendLine("    using System;");
            builder.AppendLine("    using System.Collections.Generic;");
            builder.AppendLine("    using System.Runtime.CompilerServices;");
            builder.AppendLine();
        }

        private static void AppendClassHeader(StringBuilder builder, EnumGenerationPlan plan)
        {
            builder
                .Append("    /// <summary>Generated fast-path helpers for <see cref=\"")
                .Append(plan.EnumTypeName)
                .AppendLine("\"/>.</summary>");
            builder.AppendLine(
                "    [global::System.CodeDom.Compiler.GeneratedCodeAttribute(\""
                    + GeneratorName
                    + "\", \"1.0.0.0\")]"
            );
            builder.AppendLine(
                "    [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Never)]"
            );
            builder
                .Append("    ")
                .Append(plan.AccessibilityModifier)
                .Append(" static class ")
                .Append(plan.ClassName)
                .AppendLine()
                .AppendLine("    {");
        }

        private static void AppendFlagMethods(StringBuilder builder, EnumGenerationPlan plan)
        {
            builder.AppendLine(
                "        /// <summary>Checks whether every bit of <paramref name=\"flag\"/> is set.</summary>"
            );
            builder.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static bool HasFlagNoAlloc(this ")
                .Append(plan.EnumTypeName)
                .Append(" value, ")
                .Append(plan.EnumTypeName)
                .AppendLine(" flag)");
            builder.AppendLine("        {");
            builder
                .Append("            return (unchecked((")
                .Append(plan.UnsignedCastType)
                .Append(")value) & unchecked((")
                .Append(plan.UnsignedCastType)
                .Append(")flag)) == unchecked((")
                .Append(plan.UnsignedCastType)
                .AppendLine(")flag);");
            builder.AppendLine("        }");
            builder.AppendLine();

            builder.AppendLine(
                "        /// <summary>Writes the enum's 64-bit two's-complement pattern.</summary>"
            );
            builder.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static bool TryConvertToUInt64(this ")
                .Append(plan.EnumTypeName)
                .AppendLine(" value, out ulong result)");
            builder.AppendLine("        {");
            builder
                .Append("            result = ")
                .Append(
                    plan.IsSigned ? "unchecked((ulong)(long)value);" : "unchecked((ulong)value);"
                )
                .AppendLine();
            builder.AppendLine("            return true;");
            builder.AppendLine("        }");
            builder.AppendLine();

            builder.AppendLine(
                "        /// <summary>Writes the enum's signed 64-bit serialized pattern.</summary>"
            );
            builder.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static bool TryConvertToInt64(this ")
                .Append(plan.EnumTypeName)
                .AppendLine(" value, out long result)");
            builder.AppendLine("        {");
            builder.AppendLine("            result = unchecked((long)value);");
            builder.AppendLine("            return true;");
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendNameTable(
            StringBuilder builder,
            EnumGenerationPlan plan,
            string tableName,
            bool display
        )
        {
            if (plan.Entries.Length == 0 || plan.UseSwitch)
            {
                return;
            }
            if (plan.UseArray)
            {
                AppendArrayTable(builder, plan, tableName, display);
            }
            else
            {
                AppendDictionaryTable(builder, plan, tableName, display);
            }
        }

        private static void AppendDisplayTable(StringBuilder builder, EnumGenerationPlan plan)
        {
            if (plan.Entries.Length == 0 || !plan.HasDisplayTable)
            {
                return;
            }
            AppendNameTable(builder, plan, "DisplayNames", true);
        }

        private static void AppendArrayTable(
            StringBuilder builder,
            EnumGenerationPlan plan,
            string tableName,
            bool display
        )
        {
            string[] slots = new string[plan.ArrayLength];
            foreach (EnumNameEntry entry in plan.Entries)
            {
                int index = (int)unchecked(entry.Key - plan.Minimum);
                if (index < slots.Length)
                {
                    slots[index] = display ? entry.DisplayName : entry.Name;
                }
            }

            builder
                .Append("        private static readonly string[] ")
                .Append(tableName)
                .Append(" = new string[")
                .Append(plan.ArrayLength.ToString(CultureInfo.InvariantCulture))
                .AppendLine("]");
            builder.AppendLine("        {");
            foreach (string slot in slots)
            {
                builder.Append("            ");
                if (slot == null)
                {
                    builder.Append("null");
                }
                else
                {
                    builder.Append(SymbolDisplay.FormatLiteral(slot, quote: true));
                }
                builder.AppendLine(",");
            }
            builder.AppendLine("        };");
            builder.AppendLine();
        }

        private static void AppendDictionaryTable(
            StringBuilder builder,
            EnumGenerationPlan plan,
            string tableName,
            bool display
        )
        {
            builder
                .Append("        private static readonly Dictionary<ulong, string> ")
                .Append(tableName)
                .AppendLine(" = new Dictionary<ulong, string>");
            builder.AppendLine("        {");
            foreach (EnumNameEntry entry in plan.Entries)
            {
                builder
                    .Append("            [")
                    .Append(KeyLiteral(entry.Key))
                    .Append("] = ")
                    .Append(
                        SymbolDisplay.FormatLiteral(
                            display ? entry.DisplayName : entry.Name,
                            quote: true
                        )
                    )
                    .AppendLine(",");
            }
            builder.AppendLine("        };");
            builder.AppendLine();
        }

        private static void AppendNameLookup(StringBuilder builder, EnumGenerationPlan plan)
        {
            if (plan.Entries.Length == 0)
            {
                return;
            }
            builder.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder
                .Append("        private static string FindCachedName(")
                .Append(plan.EnumTypeName)
                .AppendLine(" value)");
            builder.AppendLine("        {");
            builder.Append("            ulong key = unchecked((ulong)value);");
            builder.AppendLine();
            AppendLookupBody(builder, plan, "Names", false);
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendDisplayLookup(StringBuilder builder, EnumGenerationPlan plan)
        {
            if (plan.Entries.Length == 0 || !plan.HasDisplayTable)
            {
                return;
            }
            builder.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            builder
                .Append("        private static string FindDisplayName(")
                .Append(plan.EnumTypeName)
                .AppendLine(" value)");
            builder.AppendLine("        {");
            builder.AppendLine("            ulong key = unchecked((ulong)value);");
            AppendLookupBody(builder, plan, "DisplayNames", true);
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendLookupBody(
            StringBuilder builder,
            EnumGenerationPlan plan,
            string tableName,
            bool display
        )
        {
            if (plan.UseSwitch)
            {
                builder.AppendLine("            switch (key)");
                builder.AppendLine("            {");
                foreach (EnumNameEntry entry in plan.Entries)
                {
                    builder
                        .Append("                case ")
                        .Append(KeyLiteral(entry.Key))
                        .Append(": return ")
                        .Append(
                            SymbolDisplay.FormatLiteral(
                                display ? entry.DisplayName : entry.Name,
                                quote: true
                            )
                        )
                        .AppendLine(";");
                }
                builder.AppendLine("            }");
                builder.AppendLine("            return null;");
                return;
            }
            if (plan.UseArray)
            {
                builder
                    .Append("            ulong index = unchecked(key - ")
                    .Append(KeyLiteral(plan.Minimum))
                    .AppendLine(");");
                builder
                    .Append("            if (index < (ulong)")
                    .Append(tableName)
                    .AppendLine(".Length)");
                builder.AppendLine("            {");
                builder
                    .Append("                string name = ")
                    .Append(tableName)
                    .AppendLine("[index];");
                builder.AppendLine("                if (name != null)");
                builder.AppendLine("                {");
                builder.AppendLine("                    return name;");
                builder.AppendLine("                }");
                builder.AppendLine("            }");
            }
            else
            {
                builder
                    .Append("            if (")
                    .Append(tableName)
                    .AppendLine(".TryGetValue(key, out string name))");
                builder.AppendLine("            {");
                builder.AppendLine("                return name;");
                builder.AppendLine("            }");
            }
            builder.AppendLine("            return null;");
        }

        private static void AppendNameMethods(StringBuilder builder, EnumGenerationPlan plan)
        {
            string fallbackName =
                "global::WallstopStudios.UnityHelpers.Core.Extension.EnumNameCache<"
                + plan.EnumTypeName
                + ">.ToCachedName(value)";
            builder.AppendLine(
                "        /// <summary>Returns the cached general-format name.</summary>"
            );
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static string ToCachedName(this ")
                .Append(plan.EnumTypeName)
                .AppendLine(" value)");
            builder.AppendLine("        {");
            if (plan.Entries.Length != 0)
            {
                builder.AppendLine("            string cached = FindCachedName(value);");
                builder.AppendLine("            if (cached != null)");
                builder.AppendLine("            {");
                builder.AppendLine("                return cached;");
                builder.AppendLine("            }");
            }
            builder.Append("            return ").Append(fallbackName).AppendLine(";");
            builder.AppendLine("        }");
            builder.AppendLine();

            string fallbackDisplay =
                "global::WallstopStudios.UnityHelpers.Core.Extension.EnumDisplayNameCache<"
                + plan.EnumTypeName
                + ">.ToDisplayName(value)";
            builder.AppendLine(
                "        /// <summary>Returns the display name, falling back to the field name.</summary>"
            );
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static string ToDisplayName(this ")
                .Append(plan.EnumTypeName)
                .AppendLine(" value)");
            builder.AppendLine("        {");
            if (plan.HasDisplayTable)
            {
                if (plan.Entries.Length != 0)
                {
                    builder.AppendLine("            string cached = FindDisplayName(value);");
                    builder.AppendLine("            if (cached != null)");
                    builder.AppendLine("            {");
                    builder.AppendLine("                return cached;");
                    builder.AppendLine("            }");
                }
                builder.Append("            return ").Append(fallbackDisplay).AppendLine(";");
            }
            else
            {
                builder.AppendLine("            return ToCachedName(value);");
            }
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        private static void AppendFormatMethod(StringBuilder builder, EnumGenerationPlan plan)
        {
            builder.AppendLine(
                "        /// <summary>Writes the cached name into a character span.</summary>"
            );
            builder
                .Append("        ")
                .Append(plan.AccessibilityModifier)
                .Append(" static bool TryFormatCachedName(this ")
                .Append(plan.EnumTypeName)
                .AppendLine(" value, Span<char> destination, out int charsWritten)");
            builder.AppendLine("        {");
            builder.AppendLine("            string name = ToCachedName(value);");
            builder.AppendLine("            if (name == null || destination.Length < name.Length)");
            builder.AppendLine("            {");
            builder.AppendLine("                charsWritten = 0;");
            builder.AppendLine("                return false;");
            builder.AppendLine("            }");
            builder.AppendLine("            name.AsSpan().CopyTo(destination);");
            builder.AppendLine("            charsWritten = name.Length;");
            builder.AppendLine("            return true;");
            builder.AppendLine("        }");
        }

        private static string KeyLiteral(ulong key)
        {
            return key.ToString(CultureInfo.InvariantCulture) + "UL";
        }
    }
}
