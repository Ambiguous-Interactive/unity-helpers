namespace WallstopStudios.UnityHelpers.Proto.Generator
{
    using System;
    using System.Collections.Generic;
    using System.Text;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.Text;

    /// <summary>Registers closed BCL collection roots with their existing repeated-field codec.</summary>
    internal static class RootCollections
    {
        internal static void Emit(
            GeneratorExecutionContext context,
            IReadOnlyList<ClosureScan.TypeUse> uses,
            IReadOnlyList<IArrayTypeSymbol> arrays,
            SurrogateMap surrogates,
            List<string> registrations
        )
        {
            if (
                context.Compilation.GetTypeByMetadataName(
                    "WallstopStudios.UnityHelpers.Core.Serialization.WallstopProto.WProtoRootMarshalProvider"
                ) == null
            )
            {
                return;
            }
            SortedDictionary<string, ITypeSymbol> types = new SortedDictionary<string, ITypeSymbol>(
                StringComparer.Ordinal
            );
            foreach (ClosureScan.TypeUse use in uses)
            {
                INamedTypeSymbol type = use.Type;
                string definition = type.OriginalDefinition.ToDisplayString();
                if (
                    string.Equals(
                        definition,
                        "System.Collections.Generic.List<T>",
                        StringComparison.Ordinal
                    )
                    || string.Equals(
                        definition,
                        "System.Collections.Generic.Dictionary<TKey, TValue>",
                        StringComparison.Ordinal
                    )
                )
                {
                    if (IsClosed(type) && TypeNaming.IsNameable(type, context.Compilation))
                    {
                        types[type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)] =
                            type;
                    }
                }
            }
            foreach (IArrayTypeSymbol array in arrays)
            {
                if (
                    array.Rank == 1
                    && IsClosed(array)
                    && TypeNaming.IsNameable(array, context.Compilation)
                )
                {
                    types[array.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)] = array;
                }
            }
            NestedCollections nested = new NestedCollections("CollectionRoot", surrogates);
            Writer writer = new Writer();
            writer.Line("// <auto-generated />");
            writer.Line("#pragma warning disable");
            writer.Line("namespace WallstopStudios.UnityHelpers.Generated" + Writer.Open);
            writer.Indent();
            writer.Line("internal static class WProtoGeneratedCollectionRoots" + Writer.Open);
            writer.Indent();
            int count = 0;
            List<string> builtins = new List<string>();
            foreach (KeyValuePair<string, ITypeSymbol> pair in types)
            {
                Shape shape = nested.TryShape(pair.Value, pair.Key, "CollectionRoot", false);
                if (shape == null)
                {
                    continue;
                }
                string name = "Root" + ++count;
                writer.Line(
                    "internal static "
                        + NestedCollections.Proto
                        + ".IWProtoFormatter<"
                        + pair.Key
                        + "> "
                        + name
                        + " => "
                        + shape.ReadFormatter
                        + ";"
                );
                builtins.Add(
                    "global::WallstopStudios.UnityHelpers.Generated.WProtoGeneratedCollectionRoots."
                        + name
                );
            }
            if (count == 0)
            {
                return;
            }
            registrations.InsertRange(0, builtins);
            nested.Emit(writer);
            writer.Outdent();
            writer.Line("}");
            writer.Outdent();
            writer.Line("}");
            context.AddSource(
                "WProtoGeneratedCollectionRoots.g.cs",
                SourceText.From(writer.ToString(), Encoding.UTF8)
            );
        }

        private static bool IsClosed(ITypeSymbol type)
        {
            if (type is ITypeParameterSymbol || type.TypeKind == TypeKind.Error)
            {
                return false;
            }
            if (type is IArrayTypeSymbol array)
            {
                return IsClosed(array.ElementType);
            }
            if (type is INamedTypeSymbol named)
            {
                if (named.ContainingType != null && !IsClosed(named.ContainingType))
                {
                    return false;
                }
                foreach (ITypeSymbol argument in named.TypeArguments)
                {
                    if (!IsClosed(argument))
                    {
                        return false;
                    }
                }
            }
            return true;
        }
    }
}
